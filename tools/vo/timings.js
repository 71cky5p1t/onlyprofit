// Word timings for the induction captions, from the recorded clips. Run after re-recording: node tools/vo/timings.js
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { execFileSync, spawnSync } = require('node:child_process');
process.chdir(path.join(__dirname, '../..'));
const ctx = vm.createContext({});
vm.runInContext(fs.readFileSync('src/explainer/00-lessons.js', 'utf8') + ';globalThis.L = LESSONS; globalThis.clip = voiceClip;', ctx);
const syll = w => Math.max(1, (w.toLowerCase().replace(/[^a-z]/g, '').replace(/e$/, '').match(/[aeiouy]+/g) || []).length) + .3;
function pauses(file) {
  const dur = +execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file]).toString();
  const log = spawnSync('ffmpeg', ['-hide_banner', '-i', file, '-af', 'silencedetect=noise=-30dB:d=0.12', '-f', 'null', '-']).stderr.toString();
  const out = [], re = /silence_start: ([\d.]+)[\s\S]*?silence_end: ([\d.]+)/g;
  let m; while ((m = re.exec(log))) out.push([+m[1], Math.min(+m[2], dur)]);
  return { dur, out };
}
function align(line, { dur, out }) {
  const words = line.split(' '), w = words.map(syll);
  let start = 0, end = dur;
  if (out[0] && out[0][0] < .05) start = out.shift()[1];
  if (out.length && out[out.length - 1][1] > dur - .05) end = out.pop()[0];
  // phrase ends are words carrying punctuation; each takes the pause that best fits its share of the line
  const ends = words.map((x, i) => i).filter(i => i < words.length - 1 && /[.,?!]$/.test(words[i]));
  const total = w.reduce((a, b) => a + b, 0), cum = []; w.reduce((a, b, i) => (cum[i] = a + b), 0);
  const speech = t => { let s = t - start; for (const [a, b] of out) if (b <= t) s -= b - a; return s; };
  const talk = speech(end), fr = ends.map(i => cum[i] / total), pf = out.map(p => speech(p[0]) / talk);
  const D = Array.from({ length: ends.length + 1 }, () => Array(out.length + 1).fill(Infinity)), pick = D.map(r => r.map(() => 0));
  D[0].fill(0);
  for (let i = 1; i <= ends.length; i++) for (let j = 0; j <= out.length; j++) {
    const skip = D[i - 1][j] + .25, take = j ? D[i - 1][j - 1] + Math.abs(pf[j - 1] - fr[i - 1]) - (out[j - 1][1] - out[j - 1][0]) * .3 : Infinity;
    let best = Math.min(skip, take), via = take <= skip ? 1 : 0;
    if (j && D[i][j - 1] < best) { best = D[i][j - 1]; via = 2; }
    D[i][j] = best; pick[i][j] = via;
  }
  const at = {}; for (let i = ends.length, j = out.length; i > 0;) { const v = pick[i][j]; if (v === 2) j--; else { if (v === 1) { at[ends[i - 1]] = out[j - 1]; j--; } i--; } }
  // words spread over each phrase by syllables
  const times = []; let i0 = 0, t0 = start;
  const cuts = Object.keys(at).map(Number).sort((a, b) => a - b).concat(words.length - 1);
  for (const i1 of cuts) {
    const t1 = i1 === words.length - 1 ? end : at[i1][0], seg = w.slice(i0, i1 + 1), sum = seg.reduce((a, b) => a + b, 0);
    let acc = 0; for (const s of seg) { times.push(+(t0 + (t1 - t0) * acc / sum).toFixed(2)); acc += s; }
    i0 = i1 + 1; t0 = i1 === words.length - 1 ? end : at[i1][1];
  }
  return { times, dur: +dur.toFixed(2) };
}
const rows = ctx.L.map((l, i) => {
  const file = ['assets/audio/induction/' + ctx.clip(i) + '.mp3', 'assets/audio/induction/' + l[0] + '.mp3'].find(f => fs.existsSync(f));
  return file ? `    ${l[0]}: ${JSON.stringify(align(l[2], pauses(file)))}` : null;
}).filter(Boolean);
fs.writeFileSync('src/explainer/00-timings.js', '  // generated by tools/vo/timings.js: when each caption word is spoken, in seconds into its clip\n  const VO_TIMES = {\n' + rows.join(',\n') + '\n  };\n');
console.log('Timed', rows.length, 'clips.');
