def bar(i): return i % 8


def strum_shape(name):
  q = 'dom' if name in ('Bb13', 'E9', 'Bbalt') else 'm' if name in ('Ebm', 'Em', 'Abm') else '6'
  return [ROOT[name] + x for x in SHAPE[q]]


def riff_root(i, beat):
  # chord root under the bass note at this beat, for parallel planing
  return BASS[bar(i)][int(beat)]
