const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync('src/explainer/00-lessons.js', 'utf8') + '\nglobalThis.lessons = LESSONS;', context);
const lessons = context.lessons;
assert.equal(lessons.length, 13);
assert.equal(new Set(lessons.map(l => l[0])).size, lessons.length);
assert.ok(lessons.every(l => l.length === 4 && l.slice(0, 3).every(t => typeof t === 'string' && t.length) && l[3] > 0));
assert.ok(lessons.reduce((n, l) => n + l[3], 0) < 110);
assert.match(lessons.find(l => l[0] === 'overtime')[2], /six spare cards/);
const built = fs.readFileSync('dist/only-profit.html', 'utf8');
for (const match of built.matchAll(/<script>([\s\S]*?)<\/script>/g)) new vm.Script(match[1]);
assert.ok(built.indexOf('const LESSONS') < built.indexOf('const start = data'));
assert.ok(built.indexOf('const TEACH') < built.indexOf('const start = data'));
assert.match(fs.readFileSync('dist/viewer.html', 'utf8'), /^<meta charset="utf-8">/);
console.log('Induction: 13 chapters, under 110 seconds, six-spare rules, build syntax and initialization order passed.');
